/** Every kind not listed by subtype has a services page; `npc` and `connector` sites only show on place pages. */
export const SERVICE_KINDS: readonly FeatureKind[] = KINDS.map(([k]) => k).filter(
    k => !RESOURCE_KINDS.includes(k) && k !== 'npc' && k !== 'connector',
);

export const kindTitle = (kind: FeatureKind): string => KINDS.find(([k]) => k === kind)?.[1] ?? kind;

const kindOrder = (kind: FeatureKind): number => KINDS.findIndex(([k]) => k === kind);

export const byKind = (a: FeatureKind, b: FeatureKind): number => kindOrder(a) - kindOrder(b);

/** Ids of the form `kind:area:n` compare by kind and area, then by `n` as a number. */
export function bySiteId(a: string, b: string): number {
    const [pa, na] = [a.slice(0, a.lastIndexOf(':')), Number(a.slice(a.lastIndexOf(':') + 1))];
    const [pb, nb] = [b.slice(0, b.lastIndexOf(':')), Number(b.slice(b.lastIndexOf(':') + 1))];
    return cmp(pa, pb) || na - nb;
}

/** The repo-relative path of each page, and the link from one to another. */
export const placePath = (areaId: string): string => `wiki/places/${areaId}.md`;
export const resourcePath = (kind: FeatureKind, subtype: string): string =>
    `wiki/resources/${kind}/${slug(subtype)}.md`;
export const servicePath = (kind: FeatureKind): string => `wiki/services/${kind}.md`;

/** The relative link from the page at `from` to the page at `to`, both repo-relative. */
export function link(from: string, to: string): string {
    const a = from.split('/').slice(0, -1);
    const b = to.split('/');
    let common = 0;
    while (common < a.length && common < b.length - 1 && a[common] === b[common]) common++;
    return [...a.slice(common).map(() => '..'), ...b.slice(common)].join('/');
}

/**
 * What a site holds, as `name n` parts: by subtype, or by the features' in-game names where the kind
 * has no subtypes (a connector site reads `Ladder 1`, not `connector 1`), sorted by name.
 */
export function contents(site: Site, features: readonly Feature[]): string[] {
    const counted = new Map<string, number>();
    for (const i of site.features) {
        const f = features[i]!;
        const key = f.subtype || f.name;
        counted.set(key, (counted.get(key) ?? 0) + 1);
    }
    return [...counted].sort(([a], [b]) => cmp(a, b)).map(([k, n]) => `${k} ${n}`);
}

export interface Areas {
    /** The leaf area's name, then its parent's in parentheses: `Varrock West bank (Varrock)`. */
    label: (path: readonly string[]) => string;
}

export function areasOf(world: World): Areas {
    const byId = new Map(world.areas.map(a => [a.id, a]));
    const name = (id: string): string => byId.get(id)?.name ?? id;
    return {
        label: path => {
            const leaf = path.at(-1);
            if (leaf === undefined) return '-';
            const parent = path.at(-2);
            return parent === undefined ? name(leaf) : `${name(leaf)} (${name(parent)})`;
        },
    };
}

/** The area cell of a site row: the leaf area linked to its place page, `-` for none. */
export function areaCell(from: string, areas: Areas, path: readonly string[]): string {
    const leaf = path.at(-1);
    return leaf === undefined ? '-' : `[${areas.label(path)}](${link(from, placePath(leaf))})`;
}

/** Sites in the order a cross-area list shows them: by area path, then id. */
export const byAreaThenId = (a: Site, b: Site): number =>
    cmp(a.areaPath.join('/'), b.areaPath.join('/')) || bySiteId(a.id, b.id);
