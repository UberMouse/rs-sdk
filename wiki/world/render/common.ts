// What every rendered page shares: tile and flag formats (as the shop pages print coordinates), tables,
// the order and titles of kinds, area labels and the paths pages link by.
import type { Feature, FeatureKind, Site, Tile, World } from '../types';

/** The comment that opens every generated page. */
export const GENERATED = '<!-- Generated by wiki/world/build.ts (bun run world) from the game data. Do not edit. -->';

export const cmp = (a: number | string, b: number | string): number => (a < b ? -1 : a > b ? 1 : 0);

/** `(x, z)`, with ` L<n>` above level 0. */
export const coord = (t: Tile): string => `(${t.x}, ${t.z})${t.level > 0 ? ` L${t.level}` : ''}`;

export const yesNo = (b: boolean): string => (b ? 'yes' : 'no');

/** `1 site`, `3 sites`. */
export const count = (n: number, noun: string): string => `${n} ${noun}${n === 1 ? '' : 's'}`;

export const wilderness = (level: number): string => (level > 0 ? String(level) : '-');

/** A table row; a `|` inside a cell would end it, so it is escaped. */
const tableRow = (cells: readonly string[]): string => `| ${cells.map(c => c.replace(/\|/g, '\\|')).join(' | ')} |`;

/** A markdown table. */
export const table = (headers: readonly string[], rows: readonly (readonly string[])[]): string[] => [
    tableRow(headers),
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map(tableRow),
];

/** A file name for a subtype: config names keep their underscores, anything else becomes `-`. */
export const slug = (s: string): string => s.toLowerCase().replace(/[^a-z0-9_-]+/g, '-');

