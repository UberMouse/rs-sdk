/** Ids of the form `kind:area:n` compare by kind and area, then by `n` as a number. */
export function bySiteId(a: string, b: string): number {
    const [pa, na] = [a.slice(0, a.lastIndexOf(':')), Number(a.slice(a.lastIndexOf(':') + 1))];
    const [pb, nb] = [b.slice(0, b.lastIndexOf(':')), Number(b.slice(b.lastIndexOf(':') + 1))];
    return cmp(pa, pb) || na - nb;
}

/** The repo-relative path of each page, and the link from one to another. */
export const placePath = (areaId: string): string => `wiki/places/${areaId}.md`;
export const resourcePath = (kind: FeatureKind, subtype: string): string =>
    `wiki/resources/${kind}/${slug(subtype)}.md`;
export const servicePath = (kind: FeatureKind): string => `wiki/services/${kind}.md`;

/** The relative link from the page at `from` to the page at `to`, both repo-relative. */
export function link(from: string, to: string): string {
    const a = from.split('/').slice(0, -1);
    const b = to.split('/');
    let common = 0;
    while (common < a.length && common < b.length - 1 && a[common] === b[common]) common++;
    return [...a.slice(common).map(() => '..'), ...b.slice(common)].join('/');
}

/** A rendered page: its repo-relative path and its text. */
export type Page = readonly [path: string, text: string];

/** The game data pages read besides the world. */
export interface PageData {
    dbrows: readonly DbRow[];
    npcConfigs: ReadonlyMap<string, Config>;
    objConfigs: ReadonlyMap<string, Config>;
    /** The title each explicit `~openshop(<inv>, ..., "<title>")` call gives its inv (openshopTitles). */
    shopTitles: ReadonlyMap<string, string>;
    /** Each quest's name in the quest list, by its questlist component (`zanaris` -> `Lost City`). */
    questNames: ReadonlyMap<string, string>;
}

/** `weapon_axe` -> `weapon axe`; `glarials_tomb` -> `Glarials tomb` with `capital`. */
const words = (id: string, capital = false): string => {
    const w = id.replace(/_/g, ' ');
    return capital ? w.charAt(0).toUpperCase() + w.slice(1) : w;
};

/**
 * How a page reads a site's reach (Site.reach): `no stand` for a site with no stand tile, `-` for no
 * requirement (`[[]]`), `unreached` for none (`[]`), else each minimal set's requirements joined with ` + `,
 * the sets with ` or `. The sets are canonical as world.json has them (requirements.ts canonicalSet), and a
 * requirement reads as requirements.ts names it, with the quest list's names and the objs' names.
 */
export function reachLabel(
    world: Pick<World, 'loadoutRules'>,
    data: PageData,
): (site: Pick<Site, 'reach' | 'stand'>) => string {
    const quest = (id: string): string => data.questNames.get(id) ?? id;
    const obj = (id: string): string => first(data.objConfigs.get(id), 'name') ?? id;
    const loadout = (id: string): string => {
        const cats = Object.keys(world.loadoutRules[id]?.forbidCategories ?? {});
        const banned = [
            ...(cats.some(c => c.startsWith('weapon_')) ? ['weapons'] : []),
            ...(cats.some(c => c.startsWith('armour_')) ? ['armour'] : []),
        ];
        return `no ${banned.length ? banned.join('/') : 'banned items'} (${words(id, true)} rule)`;
    };
    const one = (s: string): string => {
        const r = parseRequirement(s);
        switch (r.kind) {
            case 'quest':
                return r.stage === undefined ? `${quest(r.quest)} done` : `${quest(r.quest)} at stage ${r.stage}`;
            case 'skill':
                return `${r.level} ${words(r.skill, true)}`;
            case 'item':
                return `${r.how === 'worn' ? 'wear' : 'carry'} ${obj(r.obj)}`;
            case 'category':
                return `${r.how === 'worn' ? 'wear' : 'carry'} any ${words(r.category)}`;
            case 'questpoints':
                return `${r.n} quest points`;
            case 'coins':
                return `${r.n} coins`;
            case 'consume':
                return `${r.n} ${obj(r.obj)} (used up)`;
            case 'members':
                return 'members';
            case 'loadout':
                return loadout(r.rule);
            case 'other':
                return r.text;
        }
    };
    return ({ reach, stand }) => {
        if (!stand) return 'no stand';
        if (!reach.length) return 'unreached';
        if (reach.some(set => !set.length)) return '-';
        return reach.map(set => set.map(one).join(' + ')).join(' or ');
    };
}

/**
 * How a page reads a site's nearest sink of one kind (Site.nearest, distance.ts): the sink's area label and the
 * run ticks to it, then `via` what the way needs, read as the Requires column reads a set; `-` for a site with no
 * stand or none that reaches it, `none` when no sink of the kind is reached under the site's own requirement sets.
 */
export function nearestLabel(
    world: World,
    data: PageData,
    kind: SinkKind,
): (site: Pick<Site, 'reach' | 'stand' | 'nearest'>) => string {
    const areas = areasOf(world);
    const requires = reachLabel(world, data);
    const byId = new Map(world.sites.map(s => [s.id, s]));
    return site => {
        if (!site.stand || !site.reach.length) return '-';
        const n = site.nearest?.[kind];
        if (!n) return 'none';
        const where = areas.label(byId.get(n.site)?.areaPath ?? []);
        const via = n.requires.length ? ` via ${requires({ reach: [n.requires], stand: site.stand })}` : '';
        return `${where === '-' ? n.site : where}, ${count(n.runTicks, 'tick')}${via}`;
    };
}

/**
 * How many of `sites` a walk from the Lumbridge spawn gets to with no requirement, how many have a stand it
 * does not reach, and how many have no stand tile (when any).
 */
export function reachSummary(sites: readonly Pick<Site, 'reach' | 'stand'>[]): string {
    const free = sites.filter(s => s.reach.some(set => !set.length)).length;
    const unreached = sites.filter(s => s.stand && !s.reach.length).length;
    const noStand = sites.filter(s => !s.stand).length;
    return (
        `${free} a walk from the Lumbridge spawn reaches with no requirement (Requires -; a quest locking the features counts), ${unreached} it does ` +
        `not reach (unreached)${noStand ? `, ${noStand} with no stand tile (no stand)` : ''}`
    );
}

/** One thing a site holds and how many. */
export interface Part {
    /** What the part counts by: a subtype (a config, inv or rock type), or the in-game name. */
    key: string;
    /** Its in-game name, or the subtype where the subtype is the clearer name (`yew`, `iron`). */
    name: string;
    n: number;
}

// Kinds whose subtype is an npc or loc config with a name of its own in game: a part reads as that
// name, with the config beside it only where another config on the page shares it (man, man2 and man3
// are all Man).
const NAMED_CONFIGS: ReadonlySet<FeatureKind> = new Set<FeatureKind>(['npc', 'pickpocket', 'stall']);

// Kinds whose name never tells two parts apart, so the key always follows it: every fishing spot is
// named Fishing spot, and a shop keeps its inv, the name the scripts open it by, beside its title.
const KEYED: ReadonlySet<FeatureKind> = new Set<FeatureKind>(['shop', 'fishing-spot']);

/**
 * The title the shop interface shows for a shop feature (shop/scripts/shop.rs2 sets it on
 * shop_template:com_76): the title of the explicit call that opens its inv (classify.ts takes the
 * inv from that call when there is one), else the npc's shop_title when it owns this inv
 * (~openshop_activenpc), else the shopkeeper's name.
 */
function shopTitle(f: Feature, data: PageData): string {
    const explicit = data.shopTitles.get(f.subtype);
    if (explicit !== undefined) return explicit;
    const cfg = f.source === 'npc' ? params(data.npcConfigs.get(f.config) ?? {}) : undefined;
    return (cfg?.get('owned_shop') === f.subtype ? cfg.get('shop_title') : undefined) ?? f.name;
}

/**
 * The key a feature counts by and the name it reads as. A bank counts by name (Banker, Bank booth,
 * Shantay chest): nine placed banker configs share Banker, and which of them stands there matters to
 * no one. Kinds with no subtype count by name too.
 */
function partOf(f: Feature, data: PageData): [key: string, name: string] {
    if (f.kind === 'shop') return [f.subtype, shopTitle(f, data)];
    if (f.kind === 'bank') return [f.name, f.name];
    if (NAMED_CONFIGS.has(f.kind) || KEYED.has(f.kind)) return [f.subtype, f.name];
    return [f.subtype || f.name, f.subtype || f.name];
}

/** The parts of a site, sorted by name then key; a part whose features differ in name joins them with ` / `. */
export function parts(site: Site, world: World, data: PageData): Part[] {
    const byKey = new Map<string, { names: Set<string>; n: number }>();
    for (const i of site.features) {
        const f = world.features[i]!;
        const [key, name] = partOf(f, data);
        const part = byKey.get(key);
        if (part) {
            part.names.add(name);
            part.n++;
        } else byKey.set(key, { names: new Set([name]), n: 1 });
    }
    return [...byKey]
        .map(([key, { names, n }]) => ({ key, name: [...names].sort(cmp).join(' / '), n }))
        .sort((a, b) => cmp(a.name, b.name) || cmp(a.key, b.key));
}

/**
 * How parts read on one page, given every part the page shows with its kind: a NAMED_CONFIGS part
 * carries its key only where another key of those kinds on the page has the same name.
 */
export function labeller(shown: readonly (readonly [FeatureKind, Part])[]): (kind: FeatureKind, part: Part) => string {
    const keysOf = new Map<string, Set<string>>();
    for (const [kind, p] of shown)
        if (NAMED_CONFIGS.has(kind)) keysOf.set(p.name, (keysOf.get(p.name) ?? new Set()).add(p.key));
    return (kind, p) =>
        KEYED.has(kind) || (NAMED_CONFIGS.has(kind) && (keysOf.get(p.name)?.size ?? 0) > 1)
            ? `${p.name} (${p.key})`
            : p.name;
}

export interface Areas {
    /** The leaf area's name, then its parent's in parentheses: `Varrock West bank (Varrock)`. */
    label: (path: readonly string[]) => string;
}

export function areasOf(world: World): Areas {
    const byId = new Map(world.areas.map(a => [a.id, a]));
    const name = (id: string): string => byId.get(id)?.name ?? id;
    return {
        label: path => {
            const leaf = path.at(-1);
            if (leaf === undefined) return '-';
            const parent = path.at(-2);
            return parent === undefined ? name(leaf) : `${name(leaf)} (${name(parent)})`;
        },
    };
}

/** The area cell of a site row: the leaf area linked to its place page, `-` for none. */
export function areaCell(from: string, areas: Areas, path: readonly string[]): string {
    const leaf = path.at(-1);
    return leaf === undefined ? '-' : `[${areas.label(path)}](${link(from, placePath(leaf))})`;
}

/** Sites in the order a cross-area list shows them: by area path, then id. */
export const byAreaThenId = (a: Site, b: Site): number =>
    cmp(a.areaPath.join('/'), b.areaPath.join('/')) || bySiteId(a.id, b.id);
