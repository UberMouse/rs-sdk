// Renders the world as the markdown agents read: wiki/places, wiki/resources, wiki/services and wiki/training, which
// are wholly generated, and the generated head of wiki/world/README.md. renderWorld is pure; the rest reads
// the game data it needs, writes the pages and removes stale ones, or lists what differs (--check).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, unlinkSync, writeFileSync } from 'fs';
import { dirname, isAbsolute, join, relative } from 'path';
import { ROOT, SCRIPTS, WORLD_JSON } from './paths';
import type { MethodModel } from './model/method';
import { link } from './render/common';
import { renderPlaces } from './render/places';
import { renderResources } from './render/resources';
import { renderServices } from './render/services';
import { renderTraining, type TrainingData } from './render/training';
import { first, parseConfigs, readConfigs } from './sources/configs';
import { readDbrows } from './sources/dbrows';
import { readCallables, readTriggers } from './sources/triggers';
import { refuseSymlink } from './stale';
import type { World } from './types';
import { cmp } from './util';

/** The folders renderWorld owns outright: a file in them that it did not render is stale. */
export const GENERATED_DIRS: readonly string[] = ['wiki/places', 'wiki/resources', 'wiki/services', 'wiki/training'];

export const README = 'wiki/world/README.md';

/** The line in README.md below which it is hand-written; the generator keeps what follows it. */
export const HAND_WRITTEN = '<!-- Hand-written below this line: build.ts keeps it as it is. -->';

export interface RenderData extends TrainingData {
    /** README.md from the line after HAND_WRITTEN to the end. */
    readmeBody: string;
}

/** The hand-written part of a README.md's text; throws when it has no HAND_WRITTEN line. */
export function readmeBody(text: string): string {
    const at = text.indexOf(`${HAND_WRITTEN}\n`);
    if (at < 0) throw new Error(`${README} has no line "${HAND_WRITTEN}"; restore it above the hand-written part`);
    return text.slice(at + HAND_WRITTEN.length + 1);
}

function readme(world: World, pages: ReadonlyMap<string, string>, body: string): string {
    const count = (dir: string): number => [...pages.keys()].filter(p => p.startsWith(`${dir}/`)).length;
    const folder = (dir: string): string => `[${dir}/](${link(README, `${dir}/`)})`;
    const roots = world.areas.filter(a => a.parent === undefined).length;
    return [
        '<!-- Generated by wiki/world/build.ts (bun run world) down to the hand-written line below. -->',
        '# World index',
        '',
        `Generated from \`server/content\` at \`${world.generatedFrom}\`: ${world.areas.length} areas (${roots} top level), ${world.features.length} features, ${world.sites.length} sites, ${world.npcSpawns.length} npc spawn clusters, in [wiki/world.json](${link(README, 'wiki/world.json')}).`,
        '',
        '| Folder | Pages | One page per |',
        '|---|---|---|',
        `| ${folder('wiki/places')} | ${count('wiki/places')} | area: the sites whose deepest area it is, by kind, then each child area with its sites summed |`,
        `| ${folder('wiki/resources')} | ${count('wiki/resources')} | resource subtype (tree, rock, fishing spot, stall, thieving chest, pickpocket target, flax, agility course): its dbrow or script data, then every site |`,
        `| ${folder('wiki/services')} | ${count('wiki/services')} | service kind (bank, shop, furnace, anvil, range, altar, ...): every site |`,
        `| ${folder('wiki/training')} | ${count('wiki/training')} | skill a curated method (wiki/world/methods.ts) trains: each method's floor XP/hr by level beside what the bots measured, and a README |`,
        '',
        HAND_WRITTEN,
        body,
    ].join('\n');
}

/**
 * Every generated page and the README, keyed by repo-relative path, in path order. Throws when two
 * pages share a path (two areas of one id, say), as one would overwrite the other.
 */
export function renderWorld(world: World, data: RenderData): Map<string, string> {
    const pages = new Map<string, string>();
    for (const [path, text] of [
        ...renderPlaces(world, data),
        ...renderResources(world, data),
        ...renderServices(world, data),
        ...renderTraining(world, data),
    ]) {
        if (pages.has(path) || path === README) throw new Error(`two pages render to ${path}`);
        pages.set(path, text);
    }
    pages.set(README, readme(world, pages, data.readmeBody));
    return new Map([...pages].sort(([a], [b]) => cmp(a, b)));
}

// `~openshop(<inv>, buy, sell, haggle, "<title>")`, its title a string literal in every call
// (shop/scripts/shop.rs2 [proc,openshop]); a call whose title is not one is left out.
const OPENSHOP = /~openshop\(\s*([a-z0-9_]+)\s*,[^;"]*"((?:[^"\\]|\\.)*)"\s*\)/g;

/** The title each explicit ~openshop call gives its inv; throws when two calls give one inv two titles. */
export function openshopTitles(bodies: readonly string[]): Map<string, string> {
    const titles = new Map<string, string>();
    for (const body of bodies)
        for (const line of body.split('\n'))
            for (const m of line.matchAll(OPENSHOP)) {
                // A call after `//` is commented out.
                if (line.slice(0, m.index).includes('//')) continue;
                const inv = m[1]!;
                const literal = m[2]!;
                // The interface shows the string's text: `\"` is a quote in it.
                const title = literal.replace(/\\(.)/g, '$1');
                const prior = titles.get(inv);
                if (prior !== undefined && prior !== title)
                    throw new Error(`~openshop calls give ${inv} two titles: "${prior}" and "${title}"`);
                titles.set(inv, title);
            }
    return new Map([...titles].sort(([a], [b]) => cmp(a, b)));
}

/** The quest list's interface, whose components are the quests by id with their names as `text`. */
export const QUESTLIST = 'player/interfaces/questlist.if';

/** Each questlist component's `text`, the quest's name in the list, by component id. */
export function questListNames(text: string): Map<string, string> {
    return new Map(
        [...parseConfigs(text)].flatMap(([id, c]): [string, string][] => {
            const name = first(c, 'text');
            return name === undefined ? [] : [[id, name]];
        }),
    );
}

/**
 * Reads the game data the pages need and the README's hand-written part (empty if no README), from ROOT; the training
 * pages rate methods with `model`, the one buildWorld resolved them with.
 */
export function readRenderData(model: MethodModel): RenderData {
    const file = join(ROOT, README);
    return {
        dbrows: readDbrows(),
        npcConfigs: readConfigs('npc'),
        objConfigs: readConfigs('obj'),
        model,
        shopTitles: openshopTitles([...readTriggers(), ...readCallables()].map(s => s.body)),
        questNames: questListNames(readFileSync(join(SCRIPTS, QUESTLIST), 'utf8')),
        readmeBody: existsSync(file) ? readmeBody(readFileSync(file, 'utf8')) : '',
    };
}

/** Every file under the generated folders, repo-relative. */
function generatedFiles(root: string): string[] {
    const walk = (dir: string): string[] =>
        existsSync(dir)
            ? readdirSync(dir, { withFileTypes: true }).flatMap(e =>
                  e.isDirectory() ? walk(join(dir, e.name)) : [relative(root, join(dir, e.name))],
              )
            : [];
    return GENERATED_DIRS.flatMap(d => walk(join(root, d))).sort(cmp);
}

/** Whether `file` holds `text`; a file that is missing or cannot be read (a directory, say) does not. */
function holds(file: string, text: string): boolean {
    try {
        return readFileSync(file, 'utf8') === text;
    } catch {
        return false;
    }
}

/**
 * The repo-relative paths whose file under `root` is not `files`' content, missing, unreadable, or
 * (inside the generated folders) not in `files` at all: what a fresh generation would change.
 */
export function drift(files: ReadonlyMap<string, string>, root: string = ROOT): string[] {
    const differ = [...files].filter(([p, text]) => !holds(join(root, p), text)).map(([p]) => p);
    const stale = generatedFiles(root).filter(p => !files.has(p));
    return [...differ, ...stale].sort(cmp);
}

/**
 * The paths writeFiles may write: world.json, the README, and files inside the generated folders.
 * A path is taken as it resolves, so `wiki/places/../../x` is outside them.
 */
function writable(p: string, root: string): boolean {
    const at = relative(root, join(root, p));
    if (at.startsWith('..') || isAbsolute(at)) return false;
    return at === relative(ROOT, WORLD_JSON) || at === README || GENERATED_DIRS.some(d => at.startsWith(`${d}/`));
}

/**
 * Writes `files` under `root` and removes the generated folders' files not among them; returns those.
 * It throws, before touching anything, on a path it does not own or a generated folder that is a
 * symlink, since a removal through one would delete files wherever the link points.
 */
export function writeFiles(files: ReadonlyMap<string, string>, root: string = ROOT): string[] {
    const foreign = [...files.keys()].filter(p => !writable(p, root));
    if (foreign.length) throw new Error(`writeFiles writes only generated files, not ${foreign.join(', ')}`);
    for (const d of GENERATED_DIRS) refuseSymlink(join(root, d));
    for (const [p, text] of files) {
        const file = join(root, p);
        if (holds(file, text)) continue;
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, text);
    }
    const stale = generatedFiles(root).filter(p => !files.has(p));
    for (const p of stale) {
        unlinkSync(join(root, p));
        // A subtype folder left empty goes too; rmdirSync refuses a folder that is not.
        const dir = dirname(join(root, p));
        if (!GENERATED_DIRS.some(d => join(root, d) === dir) && readdirSync(dir).length === 0) rmdirSync(dir);
    }
    return stale;
}
